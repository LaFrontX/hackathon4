def get_driver_rating_name(rating_score):
    """Преобразует числовую оценку в название"""
    if rating_score >= 80:
        return "няшечка", 5
    elif rating_score >= 65:
        return "чилл гай", 4
    elif rating_score >= 50:
        return "ноооормиз", 3
    elif rating_score >= 35:
        return "абобус", 2
    else:
        return "смертник", 1

def calculate_rating_score(row):
    """Вычисляет числовую оценку водителя от 0 до 100"""
    score = 100

    # Штрафы: каждый штраф минус 5 баллов
    score -= row['fines_count'] * 5

    # Превышение скорости: минус 15 баллов
    if row['has_speeding']:
        score -= 15

    # Аресты: минус 15 баллов за каждый
    score -= row['arrests_count'] * 15

    # Слишком высокая скорость: минус 10 баллов
    if row['avg_speed'] > 110:
        score -= 10
    elif row['avg_speed'] > 90:
        score -= 5

    # Ограничиваем диапазон
    score = max(0, min(100, score))

    return score

