# ==================== ШАГ 5: СОЗДАНИЕ ОЦЕНКИ И ТАРИФА ====================

"""
ОБЪЯСНЕНИЕ:
Теперь мы создаем целевую переменную (то, что будет предсказывать ML модель).

Оценка водителя (Rating) - от 1 до 5 звезд.
Формула оценки:
- Базовые 100 баллов
- Минус 5 баллов за каждый штраф
- Минус 15 баллов за превышение скорости
- Минус 10 баллов за арест
- Ограничиваем от 0 до 100
- Переводим в звезды: 80+ = 5 звезд, 65+ = 4 звезды, 50+ = 3 звезды, 35+ = 2 звезды, иначе 1 звезда
"""

def calculate_rating(row):
    """Вычисляет оценку водителя от 1 до 5 звезд"""
    score = 100

    # Штрафы: каждый штраф минус 5 баллов
    score -= row['fines_count'] * 5

    # Превышение скорости: минус 15 баллов
    if row['has_speeding']:
        score -= 15

    # Аресты: минус 10 баллов за каждый
    score -= row['arrests_count'] * 10

    # Ограничиваем диапазон
    score = max(0, min(100, score))

    # Преобразуем в звезды (1-5)
    if score >= 80:
        return 5
    elif score >= 65:
        return 4
    elif score >= 50:
        return 3
    elif score >= 35:
        return 2
    else:
        return 1

def recommend_tariff(row):
    """
    Рекомендует тариф на основе оценки и частоты поездок

    Тарифы (как в кейсе Московского транспорта):
    - Эко (590₽): до 15 поездок
    - Базовый (990₽): до 25 поездок
    - Стандартный (1590₽): до 40 поездок
    - Премиум (2990₽): безлимит
    - Бизнес (3990₽): безлимит + приоритет
    """
    rating = row['rating']
    trips = row['trips_per_month']

    if rating == 5:
        if trips > 35:
            return 'Бизнес'
        else:
            return 'Премиум'
    elif rating == 4:
        if trips > 30:
            return 'Премиум'
        elif trips > 20:
            return 'Стандартный'
        else:
            return 'Базовый'
    elif rating == 3:
        if trips > 25:
            return 'Стандартный'
        elif trips > 15:
            return 'Базовый'
        else:
            return 'Эко'
    else:
        if trips > 15:
            return 'Базовый'
        else:
            return 'Эко'

# Применяем функции
df_drivers['rating'] = df_drivers.apply(calculate_rating, axis=1)
df_drivers['recommended_tariff'] = df_drivers.apply(recommend_tariff, axis=1)

print("\n📊 Распределение оценок водителей:")
print(df_drivers['rating'].value_counts().sort_index())
print("\n📊 Распределение рекомендуемых тарифов:")
print(df_drivers['recommended_tariff'].value_counts())

# ==================== ШАГ 6: ОБУЧЕНИЕ ML МОДЕЛИ ====================

"""
ОБЪЯСНЕНИЕ:
Теперь обучаем модель Random Forest.

Что происходит:
1. Выбираем признаки (X) - то, на основе чего предсказываем:
   - количество штрафов
   - было ли превышение скорости
   - частота поездок
   - возраст водителя
   - средняя скорость

2. Выбираем цель (y) - рекомендуемый тариф

3. Кодируем текст в числа (LabelEncoder)

4. Нормализуем признаки (StandardScaler) - чтобы скорость и штрафы были в одном масштабе

5. Делим на обучение (80%) и тест (20%)

6. Обучаем Random Forest

7. Оцениваем качество
"""

print("\n" + "="*60)
print("🤖 ОБУЧЕНИЕ ML МОДЕЛИ")
print("="*60)

# Признаки для обучения
features = ['fines_count', 'has_speeding', 'trips_per_month', 'age', 'avg_speed']
X = df_drivers[features].copy()
y = df_drivers['recommended_tariff']

print(f"\n📊 Признаки для обучения: {features}")
print(f"🎯 Цель: тариф (5 вариантов)")

# Кодируем целевую переменную (текст → числа)
label_encoder = LabelEncoder()
y_encoded = label_encoder.fit_transform(y)

print(f"\n📋 Кодирование тарифов:")
for i, name in enumerate(label_encoder.classes_):
    print(f"   {name} → {i}")

# Нормализуем признаки (масштабируем)
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

print(f"\n📊 Данные подготовлены: {X_scaled.shape[0]} образцов, {X_scaled.shape[1]} признаков")

# Делим на обучение и тест
X_train, X_test, y_train, y_test = train_test_split(
    X_scaled, y_encoded, test_size=0.25, random_state=42, stratify=y_encoded
)

print(f"📚 Обучающая выборка: {len(X_train)} водителей")
print(f"🧪 Тестовая выборка: {len(X_test)} водителей")

# Обучаем модель Random Forest
print("\n🌲 Обучаем Random Forest...")
model = RandomForestClassifier(
    n_estimators=100,      # 100 деревьев в лесу
    max_depth=10,          # максимальная глубина дерева
    random_state=42
)
model.fit(X_train, y_train)

# Оцениваем качество
y_pred = model.predict(X_test)
accuracy = accuracy_score(y_test, y_pred)

print(f"\n📊 Качество модели:")
print(f"   Точность на тесте: {accuracy:.2%}")

print(f"\n📊 Детальный отчет:")
print(classification_report(y_test, y_pred, target_names=label_encoder.classes_))

# Важность признаков
feature_importance = pd.DataFrame({
    'feature': features,
    'importance': model.feature_importances_
}).sort_values('importance', ascending=False)

print(f"\n📊 Важность признаков (что влияет на выбор тарифа):")
for _, row in feature_importance.iterrows():
    print(f"   {row['feature']}: {row['importance']:.2%}")

