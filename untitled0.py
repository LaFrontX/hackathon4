def predict_tariff_from_vector(
    fines_count,
    has_speeding,
    trips_per_month,
    age,
    avg_speed,
    on_time_payments,
    late_payments,
):
    vec = np.array(
        [[
            fines_count,
            has_speeding,
            trips_per_month,
            age,
            avg_speed,
            on_time_payments,
            late_payments,
        ]],
        dtype=float,
    )
    vec_scaled = scaler.transform(vec)
    pred = int(model.predict(vec_scaled)[0])
    tariff_name = label_encoder.inverse_transform([pred])[0]

    discounts = {"роскошный максимум": 15, "sasa-lele": 10, "базовый минимум": 5, "нишиша": 0}
    return {"tariff": tariff_name, "discount": int(discounts.get(tariff_name, 0))}


def predict_tariff_row(row: pd.Series):
    return predict_tariff_from_vector(
        int(row["fines_count"]),
        int(row["has_speeding"]),
        int(row["trips_per_month"]),
        int(row["age"]),
        float(row["avg_speed"]),
        int(row["on_time_payments"]),
        int(row["late_payments"]),
    )


def apply_ml_forecast_and_popup(row: pd.Series) -> pd.Series:
    """После ML-тарифа: прогноз трат на месяц + всплывающее уведомление."""
    row_work = row.copy()
    pred = predict_tariff_row(row_work)
    row_work["ml_predicted_tariff"] = pred["tariff"]
    row_work["ml_predicted_discount"] = pred["discount"]

    # Для прогноза трат используем ML-скидку (если нужно rule-based — замени на tariff_discount)
    row_work["tariff_discount"] = pred["discount"]

    expense = forecast_monthly_expenses(row_work)
    popup = get_popup_notification(row_work)

    return pd.Series(
        {
            "ml_predicted_tariff": pred["tariff"],
            "ml_predicted_discount": pred["discount"],
            "forecast_road_cost": expense["forecast_road_cost"],
            "forecast_fines_cost": expense["forecast_fines_cost"],
            "forecast_monthly_total": expense["forecast_monthly_total"],
            "forecast_expense_note": expense["forecast_expense_note"],
            "popup_code": popup["popup_code"],
            "popup_message": popup["popup_message"],
        }
    )


