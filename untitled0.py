RUSSIAN_PLATE_LETTERS = ["А", "В", "Е", "К", "М", "Н", "О", "Р", "С", "Т", "У", "Х"]
REGIONS = ["77", "97", "99", "177", "197", "777"]


def random_birth_date(birth_year: int, rng: np.random.Generator) -> str:
    start = date(birth_year, 1, 1)
    end = date(birth_year, 12, 31)
    days = (end - start).days
    d = start + timedelta(days=int(rng.integers(0, days + 1)))
    return d.isoformat()


def random_plate(rng: np.random.Generator) -> str:
    a = str(rng.choice(RUSSIAN_PLATE_LETTERS))
    b = str(rng.choice(RUSSIAN_PLATE_LETTERS))
    c = str(rng.choice(RUSSIAN_PLATE_LETTERS))
    nums = int(rng.integers(100, 1000))
    reg = str(rng.choice(REGIONS))
    return f"{a}{nums:03d}{b}{c} {reg}"


def df_for_sqlite(df: pd.DataFrame) -> pd.DataFrame:
    """SQLite через pandas не любит python dict в ячейках."""
    out = df.copy()
    drop_cols = []
    for col in out.columns:
        if out[col].dtype == object:
            sample = out[col].dropna().head(20)
            if len(sample):
                first = sample.iloc[0]
                if isinstance(first, dict):
                    out[f"{col}_json"] = out[col].apply(
                        lambda x: json.dumps(x, ensure_ascii=False) if isinstance(x, dict) else None
                    )
                    drop_cols.append(col)
    out = out.drop(columns=[c for c in drop_cols if c in out.columns], errors="ignore")
    return out


def pick_full_name(rng: np.random.Generator) -> tuple[str, str, str]:
    """
    Возвращает (gender, full_name, last_name)
    gender: 'M' | 'F'
    """
    if rng.random() < 0.5:
        first = str(rng.choice(MALE_FIRST_NAMES))
        last = str(rng.choice(MALE_LAST_NAMES))
        return "M", f"{first} {last}", last
    first = str(rng.choice(FEMALE_FIRST_NAMES))
    last = str(rng.choice(FEMALE_LAST_NAMES))
    return "F", f"{first} {last}", last


def calculate_rating_by_rules(row) -> tuple[str, int]:
    speed = float(row["avg_speed"])
    fines = int(row["fines_count"])

    if speed > 180 or fines > 10:
        return "смертник", 1
    if speed < 70 or speed > 170 or (6 <= fines <= 10):
        return "абобус", 2
    if (70 <= speed < 90) or (150 < speed <= 170) or (3 <= fines <= 5):
        return "ноооормиз", 3
    if (90 <= speed <= 150) and (1 <= fines <= 2):
        return "чилл гай", 4
    if (90 <= speed <= 150) and fines == 0:
        return "няшечка", 5

    if 90 <= speed <= 150:
        if fines == 0:
            return "няшечка", 5
        if fines <= 2:
            return "чилл гай", 4
        if fines <= 5:
            return "ноооормиз", 3
        return "абобус", 2
    return "ноооормиз", 3


def get_tariff_by_rule(trips_per_month: int) -> tuple[str, int]:
    if trips_per_month >= 50:
        return "роскошный максимум", 15
    if trips_per_month >= 30:
        return "sasa-lele", 10
    if trips_per_month >= 15:
        return "базовый минимум", 5
    return "нишиша", 0


def synthesize_drivers(n: int, rng: np.random.Generator) -> pd.DataFrame:
    rows = []
    for driver_id in range(1, n + 1):
        gender, full_name, last_name = pick_full_name(rng)

        rating_type = str(
            rng.choice(
                ["няшечка", "чилл гай", "ноооормиз", "абобус", "смертник"],
                p=[0.25, 0.30, 0.25, 0.12, 0.08],
            )
        )

        if rating_type == "няшечка":
            avg_speed = float(rng.uniform(90, 150))
            fines_count = 0
            has_speeding = 0
            late_payments = 0
            on_time_payments = int(rng.integers(30, 60))
        elif rating_type == "чилл гай":
            avg_speed = float(rng.uniform(90, 150))
            fines_count = int(rng.integers(1, 3))
            has_speeding = int(rng.choice([0, 1], p=[0.7, 0.3]))
            late_payments = int(rng.integers(0, 2))
            on_time_payments = int(rng.integers(25, 50))
        elif rating_type == "ноооормиз":
            avg_speed = float(rng.uniform(70, 90)) if rng.random() > 0.5 else float(rng.uniform(150, 170))
            fines_count = int(rng.integers(3, 6))
            has_speeding = int(rng.choice([0, 1], p=[0.4, 0.6]))
            late_payments = int(rng.integers(1, 4))
            on_time_payments = int(rng.integers(15, 35))
        elif rating_type == "абобус":
            avg_speed = float(rng.uniform(40, 70)) if rng.random() > 0.5 else float(rng.uniform(170, 185))
            fines_count = int(rng.integers(6, 11))
            has_speeding = int(rng.choice([0, 1], p=[0.2, 0.8]))
            late_payments = int(rng.integers(3, 8))
            on_time_payments = int(rng.integers(5, 20))
        else:
            avg_speed = float(rng.uniform(180, 220))
            fines_count = int(rng.integers(11, 25))
            has_speeding = 1
            late_payments = int(rng.integers(5, 15))
            on_time_payments = int(rng.integers(0, 10))

        if rating_type == "няшечка":
            trips_per_month = int(rng.integers(15, 40))
        elif rating_type == "чилл гай":
            trips_per_month = int(rng.integers(10, 35))
        elif rating_type == "ноооормиз":
            trips_per_month = int(rng.integers(8, 30))
        elif rating_type == "абобус":
            trips_per_month = int(rng.integers(5, 25))
        else:
            trips_per_month = int(rng.integers(3, 20))

        age = int(rng.integers(18, 68))  # 18..67 включительно
        birth_year = TODAY_YEAR - age
        birth_date = random_birth_date(birth_year, rng)

        balance = float(
            max(
                100,
                min(
                    5000,
                    3000 - fines_count * 20 + int(rng.integers(-300, 500)),
                ),
            )
        )

        car_number = random_plate(rng)

        tariff_name, tariff_discount = get_tariff_by_rule(trips_per_month)

        rows.append(
            {
                "driver_id": driver_id,
                "gender": gender,
                "name": full_name,
                "last_name": last_name,
                "car_number": car_number,
                "birth_date": birth_date,
                "age": age,
                "balance": round(balance, 2),
                "fines_count": fines_count,
                "has_speeding": has_speeding,
                "avg_speed": round(avg_speed, 1),
                "trips_per_month": trips_per_month,
                "on_time_payments": on_time_payments,
                "late_payments": late_payments,
                "rating_actual_profile": rating_type,  # «истинный» профиль генератора
                "tariff_name_rule": tariff_name,
                "tariff_discount_rule": tariff_discount,
            }
        )

    df = pd.DataFrame(rows)
    df[["rating_by_rules", "rating_stars"]] = df.apply(
        lambda r: pd.Series(calculate_rating_by_rules(r)), axis=1
    )
    return df


