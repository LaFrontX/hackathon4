# ==================== ШАГ 4: ПРЕОБРАЗОВАНИЕ ДАННЫХ ====================

"""
ОБЪЯСНЕНИЕ:
Исходный датасет содержит записи об отдельных нарушениях (один штраф = одна строка).
Нам нужно преобразовать это в формат "один водитель = одна строка" с его характеристиками.

Что мы делаем:
1. Группируем записи по водителям (используем хеш номера машины или другие признаки)
2. Для каждого водителя считаем:
   - Количество штрафов
   - Было ли превышение скорости
   - Средний год выпуска авто
   - Количество арестов
3. Добавляем номер машины (генерируем)
4. Добавляем синтетические данные для полноты: частоту поездок, среднюю скорость
"""

print("\n🔄 Преобразуем записи о нарушениях в профили водителей...")

# Создаем искусственный ID водителя на основе комбинации признаков
# (в реальном проекте здесь был бы настоящий driver_id из БД)
df_raw['driver_id'] = df_raw.index % 50  # 50 уникальных водителей

# Группируем по водителям
driver_profiles = []

for driver_id in df_raw['driver_id'].unique():
    driver_data = df_raw[df_raw['driver_id'] == driver_id]

    # ========== ОСНОВНЫЕ ПРИЗНАКИ ИЗ РЕАЛЬНЫХ ДАННЫХ ==========

    # 1. Количество штрафов (сколько раз останавливали)
    fines_count = len(driver_data)

    # 2. Было ли превышение скорости
    if 'violation_type' in driver_data.columns:
        has_speeding = (driver_data['violation_type'].astype(str).str.contains('Speed', case=False, na=False)).any()
    else:
        has_speeding = np.random.choice([0, 1], p=[0.7, 0.3])

    # 3. Год выпуска авто (средний)
    if 'vehicle_year' in driver_data.columns:
        avg_vehicle_year = driver_data['vehicle_year'].mean()
    else:
        avg_vehicle_year = np.random.randint(2005, 2020)

    # 4. Количество арестов
    if 'arrest_made' in driver_data.columns:
        arrests_count = driver_data['arrest_made'].sum()
    else:
        arrests_count = 0

    # 5. Штат водителя (берем самый частый)
    if 'driver_state' in driver_data.columns:
        main_state = driver_data['driver_state'].mode()[0] if len(driver_data['driver_state'].mode()) > 0 else 'MD'
    else:
        main_state = 'MD'

    # ========== СИНТЕТИЧЕСКИЕ ПРИЗНАКИ (добавляем для полноты) ==========
    # Они нужны, потому что в реальном датасете нет некоторых данных
    # Но это нормально для хакатона - так делают все

    # Номер машины (генерируем уникальный)
    plate_letters = ''.join(np.random.choice(list('АВЕКМНОРСТУХ'), 3))
    plate_numbers = np.random.randint(100, 999)
    car_number = f"{plate_letters}{plate_numbers}"

    # Частота поездок (на основе количества штрафов)
    # Логика: чем больше штрафов, тем чаще водитель ездит
    if fines_count > 20:
        trips_per_month = np.random.randint(40, 60)
    elif fines_count > 10:
        trips_per_month = np.random.randint(25, 45)
    elif fines_count > 5:
        trips_per_month = np.random.randint(15, 30)
    else:
        trips_per_month = np.random.randint(5, 20)

    # Средняя скорость (если были штрафы за скорость - то выше)
    if has_speeding:
        avg_speed = np.random.uniform(75, 120)  # км/ч
    else:
        avg_speed = np.random.uniform(45, 75)   # км/ч

    # Баланс счета (генерируем)
    # Логика: больше штрафов → меньше денег на счету
    balance = max(100, min(5000, 3000 - fines_count * 30 + np.random.randint(-500, 500)))

    # Возраст водителя (на основе года авто)
    current_year = datetime.now().year
    if avg_vehicle_year > 2015:
        age = np.random.randint(25, 40)
    elif avg_vehicle_year > 2005:
        age = np.random.randint(35, 55)
    else:
        age = np.random.randint(45, 70)

    # Имя водителя (генерируем)
    first_names = ['Алексей', 'Дмитрий', 'Владимир', 'Сергей', 'Андрей', 'Михаил',
                   'Анна', 'Елена', 'Мария', 'Ольга', 'Татьяна', 'Ирина']
    last_names = ['Смирнов', 'Иванов', 'Кузнецов', 'Соколов', 'Попов', 'Лебедев']
    name = f"{np.random.choice(first_names)} {np.random.choice(last_names)}"

    # Дата рождения (из возраста)
    birth_year = 2024 - age
    birth_date = f"{birth_year}-{np.random.randint(1,13):02d}-{np.random.randint(1,29):02d}"

    # Собираем всё в одного водителя
    driver_profiles.append({
        'driver_id': driver_id,
        'name': name,
        'car_number': car_number,
        'birth_date': birth_date,
        'age': age,
        'balance': round(balance, 2),
        'fines_count': fines_count,
        'has_speeding': int(has_speeding),
        'avg_speed': round(avg_speed, 1),
        'trips_per_month': trips_per_month,
        'vehicle_year': int(avg_vehicle_year),
        'arrests_count': arrests_count,
        'driver_state': main_state
    })

# Создаем DataFrame с водителями
df_drivers = pd.DataFrame(driver_profiles)

# Берем 30 водителей (как нужно по заданию)
df_drivers = df_drivers.head(30).copy()
