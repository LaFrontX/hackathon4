def forecast_monthly_expenses(row) -> dict:
    """
    Прогноз трат на месяц:
    - няшечка: в основном только дорога
    - смертник: дорога + высокие штрафы/надбавки
    """
    trips = int(row["trips_per_month"])
    fines = int(row["fines_count"])
    rating = str(row["rating_by_rules"])
    discount = int(row.get("tariff_discount", 0))

    road_cost = round(trips * TOLL_PER_TRIP * (1 - discount / 100), 2)

    if rating == "няшечка":
        fines_cost = 0.0
        expense_note = "только дорога"
    elif rating == "чилл гай":
        fines_cost = round(fines * 200.0, 2)
        expense_note = "дорога + редкие штрафы"
    elif rating == "ноооормиз":
        fines_cost = round(fines * 350.0, 2)
        expense_note = "дорога + штрафы"
    elif rating == "абобус":
        fines_cost = round(fines * 550.0 + trips * 30.0, 2)
        expense_note = "дорога + штрафы + надбавки"
    else:  # смертник
        fines_cost = round(fines * 900.0 + trips * 80.0, 2)
        expense_note = "дорога + штрафы (максимум)"

    total_cost = round(road_cost + fines_cost, 2)

    return {
        "forecast_road_cost": road_cost,
        "forecast_fines_cost": fines_cost,
        "forecast_monthly_total": total_cost,
        "forecast_expense_note": expense_note,
    }


def get_popup_notification(row) -> dict:
    """
    Варианты всплывающих уведомлений (скорость / штрафы / падение рейтинга).
    """
    speed = float(row["avg_speed"])
    fines = int(row["fines_count"])
    rating = str(row["rating_by_rules"])
    stars = int(row["rating_stars"])
    profile = str(row.get("rating_actual", rating))

    # Падение рейтинга относительно «профиля» генерации
    rating_rank = {
        "няшечка": 5,
        "чилл гай": 4,
        "ноооормиз": 3,
        "абобус": 2,
        "смертник": 1,
    }
    profile_rank = rating_rank.get(profile, stars)
    current_rank = rating_rank.get(rating, stars)
    rating_dropped = current_rank < profile_rank

    if speed > 170 or speed < 70:
        return {
            "popup_code": "SPEED_WARNING",
            "popup_message": "Водите аккуратнее: скорость вне нормы — рейтинг может упасть.",
        }

    if fines >= 3:
        return {
            "popup_code": "FINES_WARNING",
            "popup_message": "Много штрафов — снизьте риск, иначе рейтинг упадёт.",
        }

    if rating_dropped:
        return {
            "popup_code": "RATING_DROP",
            "popup_message": "Рейтинг снизился из-за скорости или штрафов — водите аккуратнее.",
        }

    if rating == "смертник":
        return {
            "popup_code": "HIGH_EXPENSE_RISK",
            "popup_message": "Критический рейтинг — ожидайте повышенные траты (дорога + штрафы).",
        }

    if rating == "няшечка":
        return {
            "popup_code": "OK_DRIVER",
            "popup_message": "Отличный стиль вождения — в основном платите только за дорогу.",
        }

    return {
        "popup_code": "INFO_DEFAULT",
        "popup_message": "Следите за скоростью и штрафами, чтобы не потерять скидку на абонемент.",
    }


