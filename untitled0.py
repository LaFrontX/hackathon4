def random_birth_date(birth_year: int, rng: np.random.Generator) -> str:
    start = date(birth_year, 1, 1)
    end = date(birth_year, 12, 31)
    days = (end - start).days
    d = start + timedelta(days=int(rng.integers(0, days + 1)))
    return d.isoformat()


def df_for_sqlite(df: pd.DataFrame) -> pd.DataFrame:
    out = df.copy()

    drop_cols = []
    for col in out.columns:
        if out[col].dtype == object:
            sample = out[col].dropna().head(5)
            if len(sample) and isinstance(sample.iloc[0], dict):
                out[f"{col}_json"] = out[col].apply(
                    lambda x: json.dumps(x, ensure_ascii=False) if isinstance(x, dict) else None
                )
                drop_cols.append(col)

    out = out.drop(columns=[c for c in drop_cols if c in out.columns], errors="ignore")
    return out


def random_plate(rng: np.random.Generator, russian_letters, regions) -> str:
    a = str(rng.choice(russian_letters))
    b = str(rng.choice(russian_letters))
    c = str(rng.choice(russian_letters))
    nums = int(rng.integers(100, 1000))
    reg = str(rng.choice(regions))
    return f"{a}{nums:03d}{b}{c} {reg}"


def pick_full_name(rng, male_first, female_first, male_last, female_last):
    if rng.random() < 0.5:
        first = str(rng.choice(male_first))
